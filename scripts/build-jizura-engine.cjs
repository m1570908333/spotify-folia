const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const upstream = path.join(root, 'vendor/jizura-snapshot/852wa-JIZURA-fc16bfe');
const output = path.join(root, 'prototype/folia-stage');
const excluded = new Set(['12_ui.js']);
const files = fs.readdirSync(path.join(upstream, 'src')).filter(f => f.endsWith('.js') && !excluded.has(f)).sort();
const commit = 'fc16bfe43ea4a6c25a21f1caf04d17326de14f00';
const version = fs.readFileSync(path.join(upstream, 'VERSION'), 'utf8').trim();
const modules = files.map(file => {
  const source = fs.readFileSync(path.join(upstream, 'src', file), 'utf8');
  return {file, source, sha256: crypto.createHash('sha256').update(source).digest('hex')};
});
const manifest = {repository: 'https://github.com/852wa/JIZURA', commit, version, license: 'MIT', excluded: [...excluded], modules: modules.map(({file, sha256}) => ({file, sha256}))};
const license = fs.readFileSync(path.join(upstream, 'LICENSE'), 'utf8');
const html = fs.readFileSync(path.join(upstream, 'index.html'), 'utf8');
const muxers = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(match => match[1]).filter(source => source.includes('var Mp4Muxer='));
if (muxers.length !== 1) throw new Error('Expected one bundled mp4-muxer script');
const bundle = `/* JIZURA ${version} @ ${commit}\n${license}\nGenerated by scripts/build-jizura-engine.cjs; upstream modules are unmodified. */\nconst FoliaJizuraEngine = (() => {\nconst window = Object.create(globalThis); window.J={};\n${muxers[0]}\n${modules.map(m => '\n// SOURCE: ' + m.file + '\n' + m.source).join('\n').replaceAll('@VERSION@', version)}\nJ.FOLIA_SOURCE = ${JSON.stringify(manifest)};\nreturn J;\n})();\n`;
fs.writeFileSync(path.join(output, 'jizura-engine.js'), bundle);
fs.writeFileSync(path.join(output, 'JIZURA-LICENSE.txt'), license);
fs.copyFileSync(path.join(upstream, 'THIRD_PARTY_NOTICES.md'), path.join(output, 'JIZURA-THIRD-PARTY-NOTICES.md'));
fs.writeFileSync(path.join(output, 'jizura-source.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Bundled ${files.length} upstream runtime modules (${bundle.length} characters) at ${commit}`);
